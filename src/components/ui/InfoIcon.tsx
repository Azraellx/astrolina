// The circled "i" the app marks an explanation with — the capture HUD's
// phone-layout note, the credits dialog's report-a-problem notice. Drawn as
// strokes rather than typed as the ⓘ character, which renders jagged at this size
// (the glyph is bitmapped small in most UI faces) and varies by platform.
export function InfoIcon({ className, size = 13 }: { className?: string; size?: number }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="10" />
      <path d="M12 16v-4" />
      <path d="M12 8h.01" />
    </svg>
  );
}
